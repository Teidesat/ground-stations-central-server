-- Habilitar extensión TimescaleDB
CREATE EXTENSION IF NOT EXISTS timescaledb;

-- Tabla para el modelo TelemetryMessage rama dev
CREATE TABLE IF NOT EXISTS control_telemetrymessage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    message_type VARCHAR(2) NOT NULL DEFAULT 'TM',
    source VARCHAR(20) NOT NULL,
    destination VARCHAR(20) NOT NULL,
    timestamp TIMESTAMPTZ NOT NULL,
    subsystem VARCHAR(20) NOT NULL,
    module VARCHAR(50) NOT NULL,
    raw_data TEXT NOT NULL DEFAULT '',
    value DOUBLE PRECISION,
    unit VARCHAR(20) NOT NULL DEFAULT '',
    valid BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (id, timestamp)
);

-- Índices definidos en el modelo de Django
CREATE INDEX IF NOT EXISTS control_telemetrymessage_subsystem_module_idx 
    ON control_telemetrymessage (subsystem, module);

CREATE INDEX IF NOT EXISTS control_telemetrymessage_timestamp_subsystem_idx 
    ON control_telemetrymessage (timestamp DESC, subsystem);

-- Conversión a Hipertabla particionada por timestamp (intervalos de 7 días)
SELECT create_hypertable('control_telemetrymessage', 'timestamp', if_not_exists => TRUE);